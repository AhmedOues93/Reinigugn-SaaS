export function t(locale: Locale, key: TranslationKey | string, values: Record<string, string | number> = {}) {
  const dictionary = translations[locale] ?? translations[defaultLocale];
  let text = (dictionary as Record<string, string>)[key] ?? (de as Record<string, string>)[key] ?? key;
  for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function translator(locale: Locale) {
  return (key: TranslationKey | string, values?: Record<string, string | number>) => t(locale, key, values);
}
